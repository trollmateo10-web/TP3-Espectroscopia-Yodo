# Bloque 7: Cálculo de Constantes Físicas Finales (Estado Excitado B)
w_e = b_opt
w_e_x_e = -c_opt
dw_e = err[3]
dw_e_x_e = err[4]

D_e_cm1 = (w_e**2) / (4 * w_e_x_e)
derivada_we = (2 * w_e) / (4 * w_e_x_e)
derivada_wexe = -(w_e**2) / (4 * (w_e_x_e**2))
dD_e_cm1 = np.sqrt((derivada_we * dw_e)**2 + (derivada_wexe * dw_e_x_e)**2)

factor_eV = 8065.54
D_e_eV = D_e_cm1 / factor_eV
dD_e_eV = dD_e_cm1 / factor_eV

m_I = 126.90447
m_u = 1.660539e-27
mu_kg = (m_I / 2) * m_u
c_cm_s = 2.9979e10

k = (2 * np.pi * c_cm_s * w_e)**2 * mu_kg
dk = k * 2 * (dw_e / w_e)

hbar = 1.0545718e-34
a_morse_m = np.sqrt((4 * np.pi**2 * c_cm_s * mu_kg * w_e_x_e) / hbar)
a_morse_angstrom = a_morse_m * 1e-10

