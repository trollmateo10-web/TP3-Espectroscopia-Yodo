plt.plot(v_continuo, a1_opt + b_opt*v_continuo + c_opt*(v_continuo**2), '--', color='orange', alpha=0.8)
plt.plot(v_continuo, a0_opt + b_opt*v_continuo + c_opt*(v_continuo**2), '--', color='blue', alpha=0.8)
