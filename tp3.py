# Bloque 3: Radiografía de la FFT, Anclajes y Tendencias
from scipy.fft import rfft, rfftfreq, irfft

x = datos_filtrados['Numero de onda (cm-1)'].values
y = datos_filtrados['Absorbancia'].values

num_puntos = len(x)
x_uniforme = np.linspace(x.min(), x.max(), num_puntos)
y_interp = np.interp(x_uniforme, x, y)
espaciado = x_uniforme[1] - x_uniforme[0]

pad_size = 300
y_interp_padded = np.pad(y_interp, pad_size, mode='reflect')

yf = rfft(y_interp_padded)
xf = rfftfreq(len(y_interp_padded), espaciado)
frecuencia_corte = 0.003

# A) LA FUNDAMENTAL
yf_funda = yf.copy()
yf_funda[xf >= frecuencia_corte] = 0
y_funda_padded = irfft(yf_funda, n=len(y_interp_padded))
y_funda = np.interp(x, x_uniforme, y_funda_padded[pad_size:-pad_size])

# B) LA ESTRUCTURA FINA
yf_fina = yf.copy()
yf_fina[xf < frecuencia_corte] = 0
y_fina_padded = irfft(yf_fina, n=len(y_interp_padded))
y_fina = np.interp(x, x_uniforme, y_fina_padded[pad_size:-pad_size])

# Detección inicial de picos para el gráfico
