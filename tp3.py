# Bloque 6: Ajuste Cuadrático Simultáneo Estadístico Puro
x_concat = np.concatenate([x_v2_cuad, x_v1_cuad, x_v0_cuad])
y_concat = np.concatenate([energia_v2, energia_v1, energia_v0])

etiquetas_lobulos = np.concatenate([
    np.full(len(x_v2_cuad), 2),
    np.full(len(x_v1_cuad), 1),
    np.full(len(x_v0_cuad), 0)
])

X_matriz = np.vstack((x_concat, etiquetas_lobulos))

def modelo_compartido(X, a0, a1, a2, b, c):
    x_val = X[0]
    lobulo = X[1]
    y_calc = np.zeros_like(x_val)
    y_calc[lobulo == 0] = a0
    y_calc[lobulo == 1] = a1
    y_calc[lobulo == 2] = a2
    return y_calc + b * x_val + c * (x_val**2)

p0_estimado = [15700, 15500, 15300, 125, -1]

# Ajuste limpio, sin pesos. El error nace 100% de la dispersión de los datos.
parametros_optimos, covarianza = curve_fit(
    modelo_compartido,
    X_matriz,
    y_concat,
    p0=p0_estimado
)

a0_opt, a1_opt, a2_opt, b_opt, c_opt = parametros_optimos
err = np.sqrt(np.diag(covarianza))

print("--- PARÁMETROS DEL AJUSTE GLOBAL COMPARTIDO ---")
print(f"a0 (v''=0): {a0_opt:.2f} ± {err[0]:.2f} cm-1")
print(f"a1 (v''=1): {a1_opt:.2f} ± {err[1]:.2f} cm-1")
print(f"a2 (v''=2): {a2_opt:.2f} ± {err[2]:.2f} cm-1")
print(f"Parámetro lineal compartido (b): {b_opt:.2f} ± {err[3]:.2f} cm-1")
print(f"Parámetro cuadrático compartido (c): {c_opt:.3f} ± {err[4]:.3f} cm-1\n")

v_continuo = np.linspace(min(x_concat), max(x_concat), 200)
